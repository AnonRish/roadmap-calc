#!/usr/bin/env python3
"""Regenerate docs/REPRODUCTION.md from the bundled data."""

from __future__ import annotations

from pathlib import Path

from roadmap_calc import load_data, reproduce_all
from roadmap_calc.reproduce import counts, implied_inputs, render_markdown

ROOT = Path(__file__).resolve().parent.parent


def build() -> str:
    data = load_data()
    claims = reproduce_all(data)
    summary = counts(claims)
    low, high = implied_inputs(data)
    botec = [c for c in claims if not c.id.startswith(("phase", "analogies"))]
    sums = [c for c in claims if c.id.startswith(("phase", "analogies"))]
    lines = [
        "# Reproduction report",
        "",
        "Generated by `scripts/make_reproduction.py` from `src/roadmap_calc/data/roadmap-2026.json`",
        f"(transcribed from {data.meta['source_url']}, retrieved {data.meta['retrieved']}).",
        "",
        f"**{summary['reproduced']} reproduced, {summary['approximately_reproduced']} approximately "
        f"reproduced, {summary['not_reproduced']} not reproduced** out of {len(claims)} checkable figures.",
        "",
        "A figure is *reproduced* when a recomputation from the page's own inputs rounds to the stated",
        "value; *approximately reproduced* when the best recomputation is within 10%; otherwise *not",
        "reproduced*. Percentage sums are checked exactly. A figure that does not reproduce is not",
        "necessarily wrong: the page does not always spell out its inputs or definitions, and it describes",
        "several of its numbers as best guesses.",
        "",
        "## Safety-acceleration arithmetic",
        "",
        render_markdown(botec),
        "",
        "### The one clear discrepancy",
        "",
        "The page models safety R&D acceleration as (AI R&D acceleration) ** 0.6 and takes AI R&D",
        "accelerations of about 3x (ITAI) and 15x (superhuman coder). Those inputs give about 1.93x and",
        "5.08x, but the page states 2.2x and 6.7x. The stated endpoints would follow from inputs of about",
        f"{low:.1f}x and {high:.1f}x. The *later* figures (the 2.8x and 4.8x averages and the extra-year",
        "estimates) are consistent with the stated endpoints (6.7x is what carries through to the Min-H",
        "step), so this may be a labelling inconsistency in the inputs rather than an error that",
        "propagates, but only the authors can say which input they intended.",
        "",
        "## Effort portfolios and value split",
        "",
        render_markdown(sums),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "REPRODUCTION.md").write_text(build())
    print("wrote docs/REPRODUCTION.md")


if __name__ == "__main__":
    main()
